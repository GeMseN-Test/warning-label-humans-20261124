import os

LINE = "WARNING: Highly volatile when hungry. Operates on irrational anxiety and unfinished tasks. Do not attempt to reason with before caffeine intake."

def main() -> None:
    output_path = os.environ.get("OUTPUT_PATH", "/output/entry.txt")
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(LINE)

if __name__ == "__main__":
    main()
